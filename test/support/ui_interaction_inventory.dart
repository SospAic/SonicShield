/// **全功能点用户交互清单（R104）** —— 所有 UI 可点击控件 → 触发前/后状态 → 证据。
///
/// ## 它解决什么问题
///
/// 项目已有 3139 例宿主测试，绝大多数是 `tester.tap` / `enterText` 的真实点击，
/// 但证据**散在 200+ 个文件里**：「某个按钮到底点过没有、点前点后状态怎么变」
/// 只能靠人肉翻代码。本清单把这件事变成**机器可判**：
///
/// 1. `lib/features/**` 里**每一个含交互回调**（onPressed/onChanged/onTap/…）
///    的 UI 文件都必须在清单里出现（`r104_ui_inventory_lock_test.dart` 扫描核对）；
/// 2. 每条都要有**真实用例文件**作证据（文件存在 + 含 test 声明）；
/// 3. 每条都写明**触发前状态 / 动作 / 触发后状态**，供仿真台账逐条核对。
///
/// ## 诚实分类（不注水）
/// - `simulated: true` = 本轮 `r104_user_simulation_test.dart` **现场点击**并采集
///   前后状态快照，运行时写入 `_pt/r104_simulation_ledger.json`；
/// - `simulated: false` = 由项目既有 widget 用例真实点击覆盖（同为点击仿真，
///   不是源码文本锁），清单登记其触发前后状态与证据文件。
///
/// 与 `support/feature_point_inventory.dart`（docs/02 的 74 个 FR/NFR 追溯矩阵）
/// 是**两层**：那一层盯「需求有没有用例」，这一层盯「界面上的按钮有没有被点、
/// 点完状态有没有按预期变化」。
